"""
Proof-of-concept: reproducing the Dethlefsen-Relman antibiotic phenomenology
============================================================================

EMPIRICAL TARGET (real, published, citable):
    Dethlefsen & Relman (2011, PNAS 108:4554) followed 3 people through TWO
    courses of ciprofloxacin. Headline finding: the gut community largely
    RECOVERS after the first course (resilience) but, in susceptible subjects,
    settles into an ALTERED state that does NOT return after the second course
    (incomplete recovery = HYSTERESIS), with individualized responses.

WHAT THIS SCRIPT DOES:
    It is the mechanistic *retrodiction*. Using the spin-glass / bistable
    community of the theory, it runs the same two-course protocol and shows that
    the SAME mechanism reproduces the published pattern:
      - a 'resilient' subject (keystones recover)  -> returns after both courses
      - a 'susceptible' subject (a keystone is lost after course 1, lowering the
        barrier) -> returns after course 1 but TIPS after course 2.
    It also computes the early-warning signal (rising temporal variance) that
    precedes the irreversible transition (Scheffer 2009).

    This is a SYNTHETIC demonstration generated by the model, NOT the real OTU
    table. The companion file `pipeline_for_real_data.py` ingests a real
    abundance CSV and runs the identical diagnostics; point it at the
    Dethlefsen-Relman table to turn this retrodiction into a direct test.

Run:  python3 proof_of_concept.py
"""

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from spin_glass_microbiome import (scale_free_graph, enterotype_couplings,
                                   relax, integrate)

import warnings
warnings.filterwarnings("ignore")
np.seterr(over="ignore", invalid="ignore", divide="ignore")

OUT = "figures"


def bc(a, b):
    return np.abs(a - b).sum() / max(a.sum() + b.sum(), 1e-9)


def two_course_experiment(lose_keystone):
    """Run baseline -> course1 -> recovery -> course2 -> recovery.

    If lose_keystone is True, the top keystone species of the incumbent guild
    are knocked out (carrying capacity -> ~0) after course 1, modelling a
    non-recovering taxon. This lowers the barrier ('susceptible' subject).
    Returns (time, bray-curtis-vs-baseline, baseline).
    """
    S = 120
    A, k, _ = scale_free_graph(S, m=2, seed=3)
    guild = (np.arange(S) % 2).astype(int)
    r = np.random.default_rng(1).uniform(0.9, 1.1, S)
    J = enterotype_couplings(A, guild, w_in=0.4, w_out=1.2, sigma=0.12,
                             rng=np.random.default_rng(11))
    base = relax(np.where(guild == 0, 1.0, 0.1), r, J)

    keystone = [i for i in np.argsort(k)[::-1] if guild[i] == 0][0]  # top guild-A hub
    P, dur = 0.62, 40                          # single-course dose: sub-threshold

    def course(n_start, r_loc, t0, seg_len=140):
        def hf(t):
            f = np.zeros(S)
            if t0 <= t <= t0 + dur:
                f[guild == 0] = -P
            return f
        t, y = integrate(n_start, r_loc, J, hf, seg_len,
                         t_eval=np.linspace(0, seg_len, 280))
        return t, y

    # Both subjects share an IDENTICAL protocol and timeline:
    #   course 1 -> recovery -> course 2 -> recovery.
    # They differ only in whether the antibiotic permanently removes one
    # keystone (susceptible) or not (resilient): a barrier-lowering effect.
    segs_t, segs_y, toff = [], [], 0.0
    n = base.copy()
    r_cur = r.copy()

    t1, y1 = course(n, r_cur, 30)
    segs_t.append(t1 + toff); segs_y.append(y1); toff += t1[-1]
    n = y1[:, -1]

    if lose_keystone:                          # keystone fails to recolonise
        r_cur = r.copy(); r_cur[keystone] = -0.6
        n[keystone] *= 0.1

    t2, y2 = course(n, r_cur, 30)              # second course
    segs_t.append(t2 + toff); segs_y.append(y2); toff += t2[-1]

    T = np.concatenate(segs_t)
    Y = np.concatenate(segs_y, axis=1)
    d = np.array([bc(Y[:, i], base) for i in range(Y.shape[1])])
    return T, d, Y, base


def rolling_variance(Y, base, win=15):
    """Early-warning signal: temporal variance of the community state in a
    sliding window (proxy for critical slowing down)."""
    d = np.array([bc(Y[:, i], base) for i in range(Y.shape[1])])
    v = np.full_like(d, np.nan)
    for i in range(win, len(d)):
        v[i] = np.var(d[i - win:i])
    return v


def main():
    import os
    os.makedirs(OUT, exist_ok=True)

    T_r, d_r, Y_r, base_r = two_course_experiment(lose_keystone=False)
    T_s, d_s, Y_s, base_s = two_course_experiment(lose_keystone=True)
    v_s = rolling_variance(Y_s, base_s)

    fig, ax = plt.subplots(2, 1, figsize=(8.2, 6.6), sharex=True,
                           gridspec_kw=dict(height_ratios=[3, 1]))

    ax[0].plot(T_r, d_r, lw=2.3, color="#1b9e77", label="resilient subject (keystones recover)")
    ax[0].plot(T_s, d_s, lw=2.3, color="#d95f02", label="susceptible subject (keystone lost)")
    # the two courses (identical timeline for both subjects)
    courses = [(30, 70), (170, 210)]
    for (t0, t1) in courses:
        ax[0].axvspan(t0, t1, color="grey", alpha=0.12)
    ax[0].text(50, ax[0].get_ylim()[1]*0.93, "cipro\ncourse 1", ha="center", fontsize=8, color="grey")
    ax[0].text(190, ax[0].get_ylim()[1]*0.93, "cipro\ncourse 2", ha="center", fontsize=8, color="grey")
    ax[0].set_ylabel("community state\n(Bray-Curtis from pre-antibiotic baseline)")
    ax[0].set_title("Proof-of-concept: two-course antibiotic protocol reproduces\n"
                    "Dethlefsen-Relman (2011) incomplete recovery (hysteresis)")
    ax[0].legend(frameon=False, fontsize=9, loc="center left")

    ax[1].plot(T_s, v_s, color="#d95f02", lw=1.8)
    ax[1].set_ylabel("rolling\nvariance")
    ax[1].set_xlabel("time (days, model units)")
    ax[1].text(0.01, 0.8, "early-warning signal (rising variance) before the irreversible shift",
               transform=ax[1].transAxes, fontsize=8, color="#d95f02")

    fig.tight_layout()
    fig.savefig(f"{OUT}/fig7_proof_of_concept.png", dpi=150)
    plt.close(fig)
    print(f"[fig7] proof-of-concept written | resilient final dist={d_r[-1]:.3f}, "
          f"susceptible final dist={d_s[-1]:.3f}")


if __name__ == "__main__":
    main()
